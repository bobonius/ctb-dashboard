// Redraws lib/sardinia.mjs, the island map on the Holiday page. Not part of
// publishing; run by hand only to change the area it covers (the box below):
//   npm install --no-save world-atlas@2 topojson-client@3 d3-geo@3
//   node scripts/build-sardinia.mjs
import fs from 'fs';
import { feature } from 'topojson-client';
import { geoMercator, geoPath, geoGraticule, geoBounds } from 'd3-geo';
const topo = JSON.parse(fs.readFileSync('node_modules/world-atlas/land-10m.json'));
const W = 800, H = 1000;
const box = { type: 'Feature', geometry: { type: 'MultiPoint', coordinates: [[7.75, 38.72], [10.05, 41.45]] } };
const proj = geoMercator().fitExtent([[0, 0], [W, H]], box);
proj.clipExtent([[-2, -2], [W + 2, H + 2]]);
const path = geoPath(proj).digits(1);
// Only the islands themselves (Sardinia, Corsica and the small ones round them):
// clipping a continent-sized polygon to a box this small floods the sea.
const all = feature(topo, topo.objects.land);
const polys = all.features.flatMap((f) => (f.geometry.type === 'MultiPolygon' ? f.geometry.coordinates : [f.geometry.coordinates]))
  .filter((c) => { const [[w, s], [e, n]] = geoBounds({ type: 'Polygon', coordinates: c }); return w > 7 && e < 11 && s > 38 && n < 43.2; });
const land = path({ type: 'MultiPolygon', coordinates: polys });
const grat = path(geoGraticule().step([0.5, 0.5])());
const k = proj.scale(), [tx, ty] = proj.translate();
const out = `// Sardinia, for the Holiday page: Natural Earth 10m land (public domain, via
// the world-atlas package), projected once with a Mercator fitted to the box in
// scripts/build-sardinia.mjs and stored as SVG paths.
// Generated by scripts/build-sardinia.mjs, not hand-edited.
export const W = ${W}, H = ${H};
const K = ${k.toFixed(4)}, TX = ${tx.toFixed(4)}, TY = ${ty.toFixed(4)};
// the same Mercator the paths were drawn with, for placing pins
export const project = (lat, lon) => [TX + K * lon * Math.PI / 180,
  TY - K * Math.log(Math.tan(Math.PI / 4 + (lat * Math.PI / 180) / 2))];
export const LAND = ${JSON.stringify(land)};
export const GRID = ${JSON.stringify(grat)};
`;
fs.writeFileSync(new URL('../lib/sardinia.mjs', import.meta.url), out);
console.log('bytes', out.length);
